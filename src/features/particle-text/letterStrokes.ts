/** Pen-down centre lines, ordered as block capitals are written; y points down.
 * These describe gestures, while the live font mask supplies the final outline.
 */
export type StrokePoint = readonly [number, number];
export type LetterStroke = readonly StrokePoint[];
const arc = (
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  from: number,
  to: number
): StrokePoint[] =>
  Array.from({ length: 17 }, (_, i) => {
    const a = from + ((to - from) * i) / 16;
    return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
  });
const bowl = (top: number, bottom: number): StrokePoint[] => [
  [0.14, top],
  [0.55, top],
  ...arc(
    0.55,
    (top + bottom) / 2,
    0.32,
    (bottom - top) / 2,
    -Math.PI / 2,
    Math.PI / 2
  ),
  [0.14, bottom],
];
